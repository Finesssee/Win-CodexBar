#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn icon_table_is_sorted_for_binary_search() {
        let mut sorted = ICONS.iter().map(|(name, _)| *name).collect::<Vec<_>>();
        let original = sorted.clone();
        sorted.sort_unstable();
        assert_eq!(original, sorted, "static table must stay ASCII-sorted");
    }

    #[test]
    fn all_icons_are_valid_utf8_svg() {
        for (name, bytes) in ICONS {
            let text = std::str::from_utf8(bytes).unwrap_or_else(|e| panic!("{name}:{e}"));
            assert!(text.contains("<svg"), "{name}: must be svg markup");
        }
    }

    #[test]
    fn known_icons_are_valid_svg() {
        let bytes = icon_bytes("ProviderIcon-codex").expect("codex icon embedded");
        let text = std::str::from_utf8(bytes).expect("icons are utf-8 svg");
        assert!(text.contains("<svg"), "must be svg markup");
    }

    #[test]
    fn unknown_and_pathological_names_miss() {
        assert!(icon_bytes("ProviderIcon-nope").is_none());
        assert!(icon_bytes("../etc/passwd").is_none());
        assert!(icon_bytes("ProviderIcon-codex.svg").is_none());
        assert!(icon_bytes("").is_none());
    }

    #[test]
    fn icon_url_map_is_sorted_json_of_embedded_only() {
        let map: serde_json::Value = serde_json::from_str(&icon_url_map()).unwrap();
        let obj = map.as_object().unwrap();
        assert_eq!(obj.get("codex").unwrap(), "/icons/ProviderIcon-codex.svg");
        assert_eq!(obj.get("claude").unwrap(), "/icons/ProviderIcon-claude.svg");
        // Dash-normalized local id → upstream resource name.
        assert_eq!(
            obj.get("qwen-cloud").unwrap(),
            "/icons/ProviderIcon-qwencloud.svg"
        );
        assert!(obj.get("openaiapi").is_none(), "no asset -> no entry");
        assert!(obj.get("clawrouter").is_none(), "no such local provider");
        assert!(obj.get("synthetic").is_none(), "no such local provider");
        let keys: Vec<&String> = obj.keys().collect();
        let mut sorted = keys.clone();
        sorted.sort();
        assert_eq!(keys, sorted, "deterministic sorted output");
        // Every mapped key is a real local provider id reachable via the CLI.
        for key in obj.keys() {
            assert!(
                crate::core::cli_name_map().contains_key(key.as_str()),
                "dead provider id leaked into icon map: {key}"
            );
        }
    }

    #[test]
    fn icon_resource_for_normalizes_dash_ids() {
        assert_eq!(
            icon_resource_for("qwen-cloud"),
            Some("ProviderIcon-qwencloud")
        );
        assert_eq!(icon_resource_for("codex"), Some("ProviderIcon-codex"));
        assert!(icon_resource_for("clawrouter").is_none());
        assert!(icon_resource_for("../etc").is_none());
    }
}
